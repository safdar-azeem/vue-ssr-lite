import { createSsrProductionRequestHandler } from '../../server/runtime/SsrProductionRequestRuntime'
import { SsrRequestCancelledError } from '../../server/runtime/SsrRequestHandler'
import { registerSsrEmbeddedProductionFiles } from '../../server/runtime/SsrProductionFiles'
import { safeSsrLog } from '../../diagnostics/SsrObservability'
import { assertSsrRuntimeModuleExport, createSsrRuntimeLoadFailure } from '../../diagnostics/SsrRuntimeLoadDiagnostics'
import type { SsrHeaders } from '../../request/SsrRequestTypes'
import { normalizeDeploymentRequest } from '../DeploymentRequest'
import { getCloudflareEnv, runWithCloudflareRequestContext, type CloudflareRequestContext } from './CloudflareContext'

/** Virtual project root inside the Worker. Matches workerd's process.cwd(). */
export const CLOUDFLARE_WORKER_ROOT = '/bundle'
export const CLOUDFLARE_CLIENT_OUT_DIR = 'client'

export interface CloudflarePublicAsset {
  cacheControl: string
  contentType: string
}

export interface CloudflareWorkerOptions {
  /** Private client build artifacts keyed by path relative to the client directory. */
  files: Readonly<Record<string, string>>
  /** Classified public files keyed by request pathname (including the Vite base). */
  assets: Readonly<Record<string, CloudflarePublicAsset>>
  loadRuntime: () => Promise<unknown>
  /** Name of the Workers Static Assets binding. */
  assetsBinding?: string
}

interface AssetsBinding { fetch(request: Request): Promise<Response> }

const FORWARDED_ASSET_HEADERS = ['if-none-match', 'if-modified-since', 'range', 'if-range'] as const

const readRuntimeConfig = async (loaded: unknown): Promise<Record<string, unknown>> => {
  assertSsrRuntimeModuleExport(loaded)
  const exported = loaded && typeof loaded === 'object'
    ? (loaded as { default?: unknown }).default ?? loaded
    : loaded
  const config = typeof exported === 'function' ? await exported() : exported
  if (config == null || typeof config !== 'object' || Array.isArray(config)) {
    throw createSsrRuntimeLoadFailure('invalid-runtime-export')
  }
  return config as Record<string, unknown>
}

const plainFailure = (method: string, status = 500) => new Response(
  method === 'HEAD' ? null : status === 400 ? 'Bad Request' : 'Internal Server Error',
  { status, headers: { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' } },
)

/** Module Worker generated by `vue-ssr-lite build --target cloudflare`. No listener, no filesystem. */
export const createCloudflareWorker = (options: CloudflareWorkerOptions) => {
  const clientRoot = `${CLOUDFLARE_WORKER_ROOT}/${CLOUDFLARE_CLIENT_OUT_DIR}`
  registerSsrEmbeddedProductionFiles(Object.fromEntries(
    Object.entries(options.files).map(([file, source]) => [`${clientRoot}/${file}`, source])
  ))
  const bindingName = options.assetsBinding ?? 'ASSETS'

  const lookupAsset = (pathname: string): [string, CloudflarePublicAsset] | undefined => {
    if (Object.hasOwn(options.assets, pathname)) return [pathname, options.assets[pathname]!]
    let decoded: string
    try { decoded = decodeURIComponent(pathname) } catch { return undefined }
    return Object.hasOwn(options.assets, decoded) ? [decoded, options.assets[decoded]!] : undefined
  }

  const execute = createSsrProductionRequestHandler({
    root: CLOUDFLARE_WORKER_ROOT,
    loadRuntime: async () => {
      const config = await readRuntimeConfig(await options.loadRuntime())
      const server = (config.server ?? {}) as Record<string, unknown>
      return { ...config, server: { ...server, root: CLOUDFLARE_WORKER_ROOT, clientOutDir: CLOUDFLARE_CLIENT_OUT_DIR } }
    },
    // Reached only after host selection, global middleware and server routes,
    // exactly like the Node file server. Only classified public files qualify.
    resolveProductionAssetResponse: async (pathname, requestHeaders: SsrHeaders, method, signal) => {
      const found = lookupAsset(pathname)
      if (!found) return null
      const binding = getCloudflareEnv<Record<string, unknown>>()?.[bindingName] as AssetsBinding | undefined
      if (!binding || typeof binding.fetch !== 'function') {
        throw new Error(`[vue-ssr-lite] The Cloudflare "${bindingName}" static assets binding is unavailable.`)
      }
      const [file, asset] = found
      const headers = new Headers()
      for (const name of FORWARDED_ASSET_HEADERS) {
        const value = requestHeaders[name]
        if (typeof value === 'string') headers.set(name, value)
      }
      const upstream = await binding.fetch(new Request(new URL(encodeURI(file), 'https://assets.invalid'), {
        method: method === 'HEAD' ? 'HEAD' : 'GET', headers, signal,
      }))
      if (upstream.status === 404) {
        void upstream.body?.cancel().catch(() => undefined)
        return null
      }
      const responseHeaders = new Headers()
      for (const name of ['etag', 'last-modified', 'content-length', 'content-range', 'accept-ranges']) {
        const value = upstream.headers.get(name)
        if (value) responseHeaders.set(name, value)
      }
      responseHeaders.set('content-type', asset.contentType)
      responseHeaders.set('cache-control', asset.cacheControl)
      responseHeaders.set('x-content-type-options', 'nosniff')
      if (method === 'HEAD') void upstream.body?.cancel().catch(() => undefined)
      return new Response(method === 'HEAD' ? null : upstream.body, { status: upstream.status, headers: responseHeaders })
    },
  })

  const MAX_DISPATCH_DEPTH = 8
  const worker = {
    async fetch(request: Request, env: unknown, ctx: CloudflareRequestContext['ctx'], depth = 0): Promise<Response> {
      const url = new URL(request.url)
      if (url.protocol !== 'https:' && url.protocol !== 'http:') return plainFailure(request.method, 400)
      const headers: Record<string, string> = {}
      request.headers.forEach((value, name) => { headers[name] = value })
      // The URL Cloudflare hands the Worker is authoritative. Client Forwarded
      // and X-Forwarded-* values are discarded by the shared normalizer.
      const normalized = normalizeDeploymentRequest({
        method: request.method,
        url: `${url.pathname}${url.search}`,
        host: url.host,
        protocol: url.protocol === 'https:' ? 'https' : 'http',
        headers,
        // Like the Node transport, GET/HEAD never expose a request body.
        openBody: request.body && request.method !== 'GET' && request.method !== 'HEAD' ? () => request.body! : undefined,
      })
      const signal = request.signal ?? new AbortController().signal
      try {
        return await runWithCloudflareRequestContext(
          {
            env: env ?? {}, ctx,
            // A Worker cannot reliably fetch its own hostname. Same-origin SSR
            // data requests re-enter the full pipeline (middleware included) as
            // independent requests instead of leaving the isolate.
            dispatchOrigin: (target, init) => {
              let next: URL
              try { next = new URL(target) } catch { return undefined }
              if (next.origin !== url.origin || depth >= MAX_DISPATCH_DEPTH) return undefined
              return worker.fetch(new Request(next, init), env, ctx, depth + 1)
            },
          },
          () => execute(normalized, signal),
        )
      } catch (error) {
        if (error instanceof SsrRequestCancelledError || signal.aborted) {
          return new Response(null, { status: 499, headers: { 'cache-control': 'no-store' } })
        }
        safeSsrLog(undefined, 'error', 'ssr.transport.failed', {
          requestId: normalized.requestId, pathname: url.pathname, error,
        })
        return plainFailure(request.method)
      }
    },
  }
  return { fetch: (request: Request, env: unknown, ctx: CloudflareRequestContext['ctx']) => worker.fetch(request, env, ctx) }
}
